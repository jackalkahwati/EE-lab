ALLOWED_USES = ("benchmark_evidence", "pattern_learning", "constraint_extraction",
                "layout_review", "signoff_expectation", "component_selection_guidance")
FORBIDDEN_DEFAULT = ("direct_schematic_copy", "direct_layout_copy", "direct_bom_copy",
                     "production_reuse_without_review")

DATE_ADDED = "2026-07-06"


def manifest_schema():
    return {
        "version": "v1",
        "required_fields": ["name", "board_class", "source_name",
                            "source_url_or_local_path", "source_type", "license_status",
                            "trust_classification", "direct_reuse", "allowed_uses",
                            "forbidden_uses", "applies_to_fl1_boards", "extracted_patterns",
                            "extracted_constraints", "extracted_required_features",
                            "known_limitations", "provenance", "date_added"],
        "trust_classifications": list(TRUST),
        "reusable_trust": list(REUSABLE),
        "allowed_uses_vocabulary": list(ALLOWED_USES),
        "forbidden_uses_default": list(FORBIDDEN_DEFAULT),
        "default_direct_reuse": {"internal_firstlight": True, "licensed_reusable": True,
                                 "manufacturer_reference_only": False,
                                 "open_source_needs_license_review": False,
                                 "idea_only": False, "unknown_untrusted": False},
        "status_values": ["imported", "needs_source_file", "needs_license_review"],
    }


def _ref(name, board_class, trust, source_name, path, source_type, applies, **kw):
    direct = trust in REUSABLE
    status = kw.get("status", "imported" if (trust in REUSABLE or kw.get("local")) else "needs_source_file")
    allowed = kw.get("allowed_uses") or (
        list(ALLOWED_USES) if trust == "internal_firstlight"
        else ["benchmark_evidence", "pattern_learning", "constraint_extraction", "layout_review"]
        if trust == "manufacturer_reference_only"
        else ["benchmark_evidence", "pattern_learning", "constraint_extraction"])
    forbidden = kw.get("forbidden_uses") or (
        [] if trust == "internal_firstlight" else list(FORBIDDEN_DEFAULT))
    assert trust in TRUST
    return {
        "name": name, "board_class": board_class, "source_name": source_name,
        "source_url_or_local_path": path, "source_type": source_type,
        "license_status": kw.get("license_status",
                                 "FirstLight-owned" if trust == "internal_firstlight"
                                 else "manufacturer eval, reference-only"
                                 if trust == "manufacturer_reference_only"
                                 else "unreviewed" if trust == "open_source_needs_license_review"
                                 else "unknown"),
        "trust_classification": trust, "direct_reuse": direct,
        "allowed_uses": allowed, "forbidden_uses": forbidden,
        "applies_to_fl1_boards": applies,
        "extracted_patterns": kw.get("patterns", []),
        "extracted_constraints": kw.get("constraints", []),
        "extracted_required_features": kw.get("features", []),
        "known_limitations": kw.get("limitations", []),
        "provenance": kw.get("provenance", "FL-1 program Phase 13 D.5"),
        "date_added": DATE_ADDED, "status": status,
    }


