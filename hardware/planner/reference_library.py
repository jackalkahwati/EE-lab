def library():
    return {"version": "v1", "internal_count": len(INTERNAL), "external_count": len(EXTERNAL),
            "references": INTERNAL + EXTERNAL}


def refs_for_board(board_name):
    return [r for r in (INTERNAL + EXTERNAL)
            if board_name in r["applies_to_fl1_boards"] or "*" in r["applies_to_fl1_boards"]]


def pattern_extraction():
    """Extracted patterns/constraints per reference (evidence-only; guessed items
    stay advisory via the reference's own status)."""
    out = []
    for r in INTERNAL + EXTERNAL:
        out.append({
            "reference": r["name"], "trust": r["trust_classification"],
            "status": r["status"], "direct_reuse": r["direct_reuse"],
            "required_blocks": r["extracted_patterns"],
            "required_features": r["extracted_required_features"],
            "required_constraints": r["extracted_constraints"],
            "known_unsupported_risks": r["known_limitations"],
            "confidence": "evidence" if r["status"] == "imported" else "needs_review",
        })
    return {"version": "v1", "extractions": out}


def coverage_for(board_name):
    """Reference coverage summary for a board — feeds the benchmark scorer."""
    refs = refs_for_board(board_name)
    internal = [r for r in refs if r["trust_classification"] == "internal_firstlight"]
    manuf = [r for r in refs if r["trust_classification"] == "manufacturer_reference_only"]
    opensrc = [r for r in refs if r["trust_classification"] == "open_source_needs_license_review"]
    reusable = [r for r in refs if r["direct_reuse"]]
    needs_file = [r for r in refs if r["status"] == "needs_source_file"]
    unlicensed = [r for r in refs if r["trust_classification"] in
                  ("open_source_needs_license_review", "unknown_untrusted")]
    risk = ("high" if opensrc and not internal else "medium" if (manuf or opensrc) and internal
            else "low" if internal else "none")
    return {
        "board": board_name, "reference_count": len(refs),
        "internal_reference_coverage": len(internal),
        "manufacturer_reference_coverage": len(manuf),
        "open_source_reference_coverage": len(opensrc),
        "reusable_reference_count": len(reusable),
        "unlicensed_reference_count": len(unlicensed),
        "needs_source_file_count": len(needs_file),
        "reference_risk_level": risk,
        # score in [0,1]: internal refs carry weight; external add confidence but capped
        "reference_coverage_score": round(min(1.0, 0.5 * bool(internal) +
                                          0.15 * min(len(internal), 2) +
                                          0.1 * min(len(manuf) + len(opensrc), 2)), 2),
    }


